type Colors = Partial<ThemeTokens['colors']>;
const tokens = (
  colors: Colors,
  extra: Partial<Omit<ThemeTokens, 'colors' | 'typography'>> & {
    typography?: Partial<ThemeTokens['typography']>;
  } = {},
): ThemeTokens => ({
  ...DEFAULT_TOKENS,
  ...extra,
  colors: { ...DEFAULT_TOKENS.colors, ...colors },
  typography: { ...DEFAULT_TOKENS.typography, ...(extra.typography ?? {}) },
});

const theme = (t: Omit<ThemeDefinition, 'decorationAssetIds' | 'status' | 'isDefault'> &
  Partial<Pick<ThemeDefinition, 'status' | 'isDefault'>>): ThemeDefinition => ({
  status: 'Published',
  isDefault: false,
  decorationAssetIds: [],
  ...t,
});

