const yearly = (
  id: string,
  themeId: string,
  label: string,
  startsAt: string,
  endsAt: string,
  priority: number,
): ThemeSchedule => ({
  id,
  themeId,
  label,
  startsAt,
  endsAt,
  priority,
  recurrence: 'Yearly',
  enabled: true,
});

const once = (
  id: string,
  themeId: string,
  label: string,
  startsAt: string,
  endsAt: string,
  priority: number,
): ThemeSchedule => ({ ...yearly(id, themeId, label, startsAt, endsAt, priority), recurrence: 'None' });

